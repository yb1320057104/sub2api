package service

import (
	"context"
	"errors"
	"math"
	"strings"
	"time"
)

// CyberPolicyAuditBlockInput identifies a server-owned audit decision: an
// immediate rejection or a charge_allow snapshot consumed after completion.
// It deliberately contains no request body, token or client-supplied amount.
type CyberPolicyAuditBlockInput struct {
	EventKey     string
	RequestID    string
	UserID       int64
	GroupID      *int64
	Model        string
	Source       string
	PolicyAction string
	RiskScore    *float64
	RiskLevel    string
}

// RecordAuditBlock never creates synthetic usage. The insert trigger snapshots
// the independent ranking scope and atomically updates its existing counter.
// EventKey is generated by the gateway, not supplied by the API client.
func (s *CyberPolicyService) RecordAuditBlock(ctx context.Context, input CyberPolicyAuditBlockInput) error {
	if input.PolicyAction == "" {
		input.PolicyAction = "block"
	}
	if input.PolicyAction != "block" {
		return errors.New("invalid audit block action")
	}
	return s.recordAuditAction(ctx, input, 0, time.Time{})
}

// RecordAuditUsage links a completed, normally billed request to its audit
// decision. SQL reads the immutable cost from the real usage row; callers never
// supply a penalty amount. Upstream policy refusals retain their original path.
func (s *CyberPolicyService) RecordAuditUsage(ctx context.Context, input CyberPolicyAuditBlockInput, usage *UsageLog) error {
	if usage == nil || usage.ID <= 0 || usage.CreatedAt.IsZero() || usage.UserID != input.UserID ||
		usage.EffectiveRequestType() == RequestTypeCyberBlocked || input.PolicyAction != "charge_allow" ||
		!sameCyberAuditGroup(usage.GroupID, input.GroupID) {
		return errors.New("invalid audit usage identity")
	}
	return s.recordAuditAction(ctx, input, usage.ID, usage.CreatedAt)
}

func sameCyberAuditGroup(a, b *int64) bool {
	return (a == nil && b == nil) || (a != nil && b != nil && *a == *b)
}

func (s *CyberPolicyService) recordAuditAction(ctx context.Context, input CyberPolicyAuditBlockInput, usageID int64, usageAt time.Time) error {
	if s == nil || s.db == nil {
		return errors.New("cyber audit database unavailable")
	}
	if input.UserID <= 0 || input.EventKey == "" || len(input.EventKey) > 128 ||
		(input.GroupID != nil && *input.GroupID <= 0) {
		return errors.New("invalid cyber audit identity")
	}
	if input.RiskScore != nil && (math.IsNaN(*input.RiskScore) || math.IsInf(*input.RiskScore, 0) || *input.RiskScore < 0 || *input.RiskScore > 100) {
		return errors.New("invalid cyber audit score")
	}
	switch input.RiskLevel {
	case "", "none", "low", "medium", "high", "critical":
	default:
		return errors.New("invalid cyber audit risk level")
	}
	switch input.Source {
	case "content_audit", "prompt_audit", "combined_audit":
	default:
		return errors.New("invalid cyber audit source")
	}
	bounded := func(value string, max int) string {
		runes := []rune(strings.ReplaceAll(strings.TrimSpace(value), "\x00", ""))
		if len(runes) > max {
			runes = runes[:max]
		}
		return string(runes)
	}
	var usageIDValue, usageAtValue any
	if usageID > 0 {
		usageIDValue, usageAtValue = usageID, usageAt
	}
	result, err := s.db.ExecContext(ctx, `INSERT INTO cyber_policy_audit_blocks
		(event_key,request_id,user_id,group_id,model,source,policy_action,risk_score,risk_level,usage_id,usage_created_at)
		VALUES($1,$2,$3,$4,$5,$6,$7,$8,NULLIF($9,''),$10,$11)
		ON CONFLICT DO NOTHING`, input.EventKey, bounded(input.RequestID, 128), input.UserID,
		input.GroupID, bounded(input.Model, 512), input.Source, input.PolicyAction, input.RiskScore, input.RiskLevel, usageIDValue, usageAtValue)
	if err != nil {
		return err
	}
	count, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if count > 0 && s.authInvalidator != nil {
		s.authInvalidator.InvalidateAuthCacheByUserID(ctx, input.UserID)
	}
	return nil
}
